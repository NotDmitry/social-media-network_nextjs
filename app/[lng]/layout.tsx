import type { Metadata } from 'next';
import { Inter, Poppins } from 'next/font/google';
import { I18nProvider } from 'next-i18next/client';
import { AppRouterCacheProvider } from '@mui/material-nextjs/v16-appRouter';
import AppInitializer from '@/_app/AppInitializer';
import StoreProvider from '@/_app/StoreProvider';
import { ThemeProvider } from '@mui/material/styles';
import { muiGlobalTheme } from '@/_app/muiThemeConfig';
import { getT, getResources, generateI18nStaticParams } from '@/_app/i18n/i18n.server';
import '@/_app/styles/globals.css';
import Footer from './_components/Footer';
import HeaderVariantPicker from './_components/HeaderVariantPicker';
import './layout-style.css';

const poppins = Poppins({
  subsets: ['latin'],
  variable: '--font-poppins',
  weight: ['400', '500', '600'],
});

const inter = Inter({
  subsets: ['latin', 'cyrillic'],
  variable: '--font-inter',
});

export const metadata: Metadata = {
  title: 'Social Media Network',
  description: 'Generated by create next app',
};

export async function generateStaticParams() {
  return generateI18nStaticParams();
}

export default async function RootLayout({ children, params }: LayoutProps<'/[lng]'>) {
  const { lng } = await params;
  const { i18n } = await getT();
  const resources = getResources(i18n);

  return (
    <html lang={lng} className={`${poppins.variable} ${inter.variable}`}>
      <body>
        <I18nProvider language={lng} resources={resources}>
          <StoreProvider>
            <AppInitializer />
            <AppRouterCacheProvider options={{ enableCssLayer: true }}>
              <ThemeProvider theme={muiGlobalTheme}>
                <div className='layout-wrapper'>
                  <HeaderVariantPicker />
                  <main className='layout-main'>
                    {children}
                  </main>
                  <Footer />
                </div>
              </ThemeProvider>
            </AppRouterCacheProvider>
          </StoreProvider>
        </I18nProvider>
      </body>
    </html>
  );
}
